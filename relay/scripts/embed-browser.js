// Copies the browser functions into a module the worker can import.
// Run this after editing relay-codec.fn.js, setup-page.fn.js, or qrcode.vendor.js:
//   node scripts/embed-browser.js
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..", "src");
const codec = readFileSync(join(root, "relay-codec.fn.js"), "utf8");
const page = readFileSync(join(root, "setup-page.fn.js"), "utf8");
// qrcode-generator 1.4.4 by Kazuhiko Arase, MIT license. Draws the iPhone QR code.
const qr = readFileSync(join(root, "qrcode.vendor.js"), "utf8");
const out = `// Generated by scripts/embed-browser.js. Do not edit by hand.
export const CODEC_SOURCE = ${JSON.stringify(codec)};
export const PAGE_SOURCE = ${JSON.stringify(page)};
export const QR_SOURCE = ${JSON.stringify(qr)};
`;
writeFileSync(join(root, "browser-sources.js"), out);
console.log("wrote src/browser-sources.js");
